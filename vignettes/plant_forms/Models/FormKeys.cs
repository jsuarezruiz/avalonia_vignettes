namespace PlantForms.Models;

/// <summary>
/// The names the form's values are stored under. Port of <c>FormKeys</c>.
/// </summary>
public static class FormKeys
{
    /// <summary>
    /// The order's special instructions.
    /// </summary>
    public const string Instructions = "instructions";

    /// <summary>
    /// The customer's first name.
    /// </summary>
    public const string FirstName = "first_name";

    /// <summary>
    /// The customer's last name.
    /// </summary>
    public const string LastName = "last_name";

    /// <summary>
    /// The country shipped to.
    /// </summary>
    public const string Country = "country";

    /// <summary>
    /// The street address.
    /// </summary>
    public const string Address = "address";

    /// <summary>
    /// The apartment or suite.
    /// </summary>
    public const string Apt = "apt";

    /// <summary>
    /// The city.
    /// </summary>
    public const string City = "city";

    /// <summary>
    /// The postal or zip code.
    /// </summary>
    public const string Postal = "postal";

    /// <summary>
    /// The company.
    /// </summary>
    public const string Company = "company";

    /// <summary>
    /// The email address.
    /// </summary>
    public const string Email = "email";

    /// <summary>
    /// The phone number.
    /// </summary>
    public const string Phone = "phone";

    /// <summary>
    /// The card number.
    /// </summary>
    public const string CardNumber = "ccNumber";

    /// <summary>
    /// The cardholder's name.
    /// </summary>
    public const string CardName = "ccName";

    /// <summary>
    /// The card's security code.
    /// </summary>
    public const string CardCode = "ccCode";

    /// <summary>
    /// The card's expiry date.
    /// </summary>
    public const string CardExpiry = "ccExpDate";

    /// <summary>
    /// The discount code.
    /// </summary>
    public const string Coupon = "coupon";
}
